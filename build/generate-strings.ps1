<#
.SYNOPSIS
  Regenerates src/AssemblyStudio.App/Shell/Strings.cs from Strings.resx (NFR-032).

.DESCRIPTION
  WPF's markup pass runs before the resx strongly-typed generator, so x:Static references in XAML
  can't see a generated designer class. The accessor is therefore generated by this script and
  committed. Run it after editing Strings.resx:

    powershell -ExecutionPolicy Bypass -File build/generate-strings.ps1
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$resx = Join-Path $root 'src/AssemblyStudio.App/Shell/Strings.resx'
$out = Join-Path $root 'src/AssemblyStudio.App/Shell/Strings.cs'

[xml]$doc = Get-Content -LiteralPath $resx -Raw -Encoding UTF8
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// <auto-generated>')
$lines.Add('// Generated from Strings.resx by build/generate-strings.ps1. Regenerate both together.')
$lines.Add('// </auto-generated>')
$lines.Add('using System.Globalization;')
$lines.Add('using System.Resources;')
$lines.Add('')
$lines.Add('namespace AssemblyStudio.App.Shell;')
$lines.Add('')
$lines.Add('/// <summary>User-facing shell strings (NFR-032), read from <c>Strings.resx</c> for the current UI culture.</summary>')
$lines.Add('public static class Strings')
$lines.Add('{')
$lines.Add('    private static readonly ResourceManager Resources = new("AssemblyStudio.App.Shell.Strings", typeof(Strings).Assembly);')
$lines.Add('')
$lines.Add('    private static string Get(string name) => Resources.GetString(name, CultureInfo.CurrentUICulture) ?? name;')

foreach ($data in $doc.root.data) {
    $name = $data.name
    if ($name -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { throw "Invalid resource name: $name" }
    $value = ($data.value -replace '\r?\n', ' ')
    $summary = [System.Security.SecurityElement]::Escape($value)
    $lines.Add('')
    $lines.Add("    /// <summary>$summary</summary>")
    $lines.Add("    public static string $name => Get(nameof($name));")
}

$lines.Add('}')
$text = ($lines -join "`n") + "`n"
[System.IO.File]::WriteAllText($out, $text, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $out ($($doc.root.data.Count) strings)"
