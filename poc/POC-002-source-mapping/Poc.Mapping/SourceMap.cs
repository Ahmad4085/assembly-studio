using System.Text.RegularExpressions;

namespace Poc.Mapping;

/// <summary>A source location the user wrote (file + 1-based line).</summary>
public readonly record struct SourceLocation(string File, int Line);

/// <summary>A contiguous range of the image produced by one listing row.</summary>
public sealed record MappedRange(
    int Address, int Length, SourceLocation Location, bool FromMacroExpansion, string Section,
    IReadOnlyList<byte?> Bytes, bool IsReserved, int ListingIndex);

/// <summary>
/// Source line ↔ absolute address mapping built from a NASM listing and map (POC-002, OQ-009).
/// Macro-expanded bytes are attributed to the line that invoked the macro; included-file lines to that file.
/// </summary>
public sealed partial class SourceMap
{
    [GeneratedRegex(@"^\s*%include\s+[""<](?<path>[^"">]+)["">]", RegexOptions.IgnoreCase)]
    private static partial Regex IncludeLine();

    [GeneratedRegex(@"^\s*\[?\s*(?:section|segment)\s+(?<name>[^\s\],]+)", RegexOptions.IgnoreCase)]
    private static partial Regex SectionLine();

    private sealed record Frame(int Level, bool IsMacro, string File, SourceLocation Invoker);

    public IReadOnlyList<MappedRange> Ranges { get; }
    public MapFile Map { get; }
    public IReadOnlyList<ListingRow> Rows { get; }

    private SourceMap(IReadOnlyList<MappedRange> ranges, MapFile map, IReadOnlyList<ListingRow> rows) => (Ranges, Map, Rows) = (ranges, map, rows);

    public static SourceMap Build(string mainFile, string listingText, string mapText)
    {
        var map = MapFile.Parse(mapText);
        var rows = Listing.Parse(listingText);
        var ranges = new List<MappedRange>();
        var stack = new Stack<Frame>();
        stack.Push(new Frame(0, false, Path.GetFullPath(mainFile), default));
        string section = ".text";
        ListingRow? previous = null;

        foreach (var row in rows)
        {
            if (row.ErrorText is not null) continue;

            while (stack.Peek().Level > row.Level) stack.Pop();
            if (row.Level > stack.Peek().Level)
            {
                var parent = stack.Peek();
                var inc = previous is null ? null : IncludeLine().Match(previous.Source);
                if (inc is { Success: true })
                {
                    // NASM searches relative to its working directory (the main file's folder here); fall back to the includer's folder.
                    string rel = inc.Groups["path"].Value;
                    string viaMain = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(Path.GetFullPath(mainFile))!, rel));
                    string viaIncluder = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(parent.IsMacro ? parent.Invoker.File : parent.File)!, rel));
                    stack.Push(new Frame(row.Level, false, File.Exists(viaMain) ? viaMain : viaIncluder, default));
                }
                else
                {
                    var invoker = previous is null ? default : Resolve(parent, previous.LineNumber);
                    stack.Push(new Frame(row.Level, true, parent.File, invoker));
                }
            }

            var sec = SectionLine().Match(row.Source);
            if (sec.Success) section = sec.Groups["name"].Value;

            if (row.Offset is int off && row.ByteCount > 0)
            {
                if (!map.Sections.TryGetValue(section, out var s))
                    throw new InvalidDataException($"Section '{section}' from the listing is missing in the map.");
                var frame = stack.Peek();
                ranges.Add(new MappedRange(s.Vstart + off, row.ByteCount, Resolve(frame, row.LineNumber), frame.IsMacro,
                    section, row.Bytes, row.IsReserved, row.Index));
            }
            previous = row;
        }
        return new SourceMap(ranges, map, rows);
    }

    private static SourceLocation Resolve(Frame frame, int lineNumber) =>
        frame.IsMacro ? frame.Invoker : new SourceLocation(frame.File, lineNumber);

    /// <summary>Source line for an absolute address (debugger: current instruction → line).</summary>
    public SourceLocation? LineAt(int address) =>
        Ranges.FirstOrDefault(r => !r.IsReserved && address >= r.Address && address < r.Address + r.Length)?.Location;

    /// <summary>First address generated by a source line (breakpoint placement); null if the line generates no bytes.</summary>
    public int? FirstAddressOf(string file, int line)
    {
        string full = Path.GetFullPath(file);
        return Ranges.Where(r => r.Location.Line == line && string.Equals(r.Location.File, full, StringComparison.OrdinalIgnoreCase))
                     .Select(r => (int?)r.Address).Min();
    }
}
